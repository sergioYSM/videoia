// replica/design/tokens.json -> app/tokens.css + tailwind.tokens.cjs (single source of truth)
import { readFileSync, writeFileSync } from 'node:fs';
const t = JSON.parse(readFileSync('replica/design/tokens.json', 'utf8'));
const css = [':root {'];
for (const [k, v] of Object.entries(t.color)) css.push(`  --color-${k}: ${v};`);
css.push(`  --font-sans: ${t.font.sans};`, `  --font-mono: ${t.font.mono};`);
for (const [k, v] of Object.entries(t.radius)) css.push(`  --radius-${k}: ${v}px;`);
for (const [k, v] of Object.entries(t.shadow)) css.push(`  --shadow-${k}: ${v};`);
for (const [k, v] of Object.entries(t.layout)) if (typeof v === 'number') css.push(`  --${k}: ${v}px;`);
css.push('}');
writeFileSync('app/tokens.css', `/* Generated by scripts/tokens.mjs from replica/design/tokens.json. Do not edit. */\n${css.join('\n')}\n`);
const colors = Object.fromEntries(Object.keys(t.color).map((k) => [k, `var(--color-${k})`]));
const fontSize = Object.fromEntries(Object.entries(t.type).map(([k, v]) => [k, [`${v.size}px`, `${v.line}px`]]));
const borderRadius = Object.fromEntries(Object.keys(t.radius).map((k) => [k, `var(--radius-${k})`]));
writeFileSync('tailwind.tokens.cjs', `// Generated. Do not edit.\nmodule.exports = ${JSON.stringify({ colors: { transparent: 'transparent', current: 'currentColor', ...colors }, fontSize, borderRadius }, null, 2)};\n`);
console.log(`tokens: ${Object.keys(t.color).length} colours`);
